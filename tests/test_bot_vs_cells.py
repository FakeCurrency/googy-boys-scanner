"""reviews/2026-09-24-bot-vs-cells.md quotes the live bot gate; this holds it to it.

The note's predicates block is generated by scripts/bot_vs_cells.py from
config, and each line of it is ALSO pinned here against the behaviour of the
code it describes -- so the note goes stale loudly, not silently:
  * change a bot constant and the committed block no longer equals what the
    script would print;
  * change what the gate reads (grade_raw, the plan's entry, a missing
    level_tf) and the behavioural pin for that line goes red.
When one fails after a deliberate rule change, re-run the script and commit
the regenerated note in the same PR -- that is the point of the pin.

The classifier and the freshness mirror are tested on synthetic rows only:
journal/ is live data and never a test fixture.
"""

