def _row(plan_entry=100.0, stop=90.0, grade_raw="A+", grade="A+", tf="1W", trigger="reclaim",
         direction="LONG", name="Operating Co", sector="Industrials"):
    plan = {"entry": plan_entry, "stop": stop, "armed": True, "entry_trigger": trigger,
            "rr": 2.0, "scale": [0.25, 0.5, 0.15]}
    risk = abs(plan_entry - stop)
    sign = 1 if direction == "LONG" else -1
    plan.update(tp1=plan_entry + sign * risk, tp2=plan_entry + sign * 2 * risk,
                tp3=plan_entry + sign * 3 * risk)
    return {"symbol": "X", "name": name, "sector": sector, "dir": direction, "grade": grade,
            "grade_raw": grade_raw, "plans": {tf: plan}, "data_age_days": 0}


def test_direction_long_only():
    assert _block()["direction"] == "long only" and config.VIVEK_BOT_ALLOW_SHORTS is False
    assert vb.evaluate_setup(_row(direction="SHORT", stop=110.0))["code"] == "shorts_disabled"


def test_grades_and_their_source_is_grade_raw():
    b = _block()
    assert tuple(g.strip() for g in b["grades"].split(",")) == config.VIVEK_BOT_GRADES
    assert b["grade_source"] == "grade_raw"
    # the displayed grade says A+, the raw grade says B+: the gate reads raw
    assert vb.evaluate_setup(_row(grade="A+", grade_raw="B+"))["code"] == "grade_excluded"
    assert vb.evaluate_setup(_row(grade="B+", grade_raw="A"))["take"] is True


def test_the_cells_and_the_walk_order():
    b = _block()
    cells = [c.strip() for c in b["cells"].split(",")]
    assert cells == [f"{tf} {et}" for tf, ets in config.VIVEK_BOT_ENTRY_CELLS.items() for et in ets]
    assert [t.strip() for t in b["cell_walk"].split(">")] == list(config.VIVEK_BOT_ENTRY_CELLS)
    for cell in cells:
        tf, et = cell.split()
        assert vb.evaluate_setup(_row(tf=tf, trigger=et))["take"] is True, cell
    for tf, et in (("1D", "reclaim"), ("3D", "break"), ("1W", "retest")):
        assert vb.evaluate_setup(_row(tf=tf, trigger=et))["code"] == "no_cell_plan", (tf, et)


def test_the_level_gate_and_a_missing_level_is_dropped():
    b = _block()
