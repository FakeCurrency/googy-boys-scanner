bvc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bvc)


def _block() -> dict:
    m = re.search(r"The predicates, as the code reads today.*?```text\n(.*?)```", NOTE, re.S)
    assert m, "the note lost its predicates block"
    return {k.strip(): v.strip() for k, v in
            (line.split("=", 1) for line in m.group(1).strip().splitlines())}


