# -- the classifier --------------------------------------------------------

def _pos(**kw):
    base = {"id": "X:long:1W:2026-09-22", "symbol": "X", "name": "Operating Co",
            "sector": "Industrials", "direction": "long", "grade": "A+", "timeframe": "1W",
            "entry_type": "reclaim", "level_tf": "weekly", "entry": 100.0, "risk": 20.0,
            "signal_entry": 100.0, "entry_date": "2026-08-10", "_market": "nasdaq",
            "_side": "open"}
    base.update(kw)
    return base


def test_an_in_cell_position():
    c = bvc.classify(_pos())
    assert c["cls"] == "in" and c["why"] == [] and c["plan_stop"] == pytest.approx(20.0)


@pytest.mark.parametrize("kw,reason", [
    ({"timeframe": "1D"}, "1D reclaim is not a cell"),
    ({"level_tf": "h4"}, "h4 level"),
    ({"risk": 30.0}, "stop 30.0%"),
    ({"direction": "short"}, "short"),
    ({"name": "Some Index ETF"}, "fund/REIT"),
])
def test_each_failing_predicate_is_named(kw, reason):
    c = bvc.classify(_pos(**kw))
    assert c["cls"] == "out" and reason in c["why"], c


def test_a_missing_level_is_unknown_not_out():
    c = bvc.classify(_pos(level_tf=None))
    assert c["cls"] == "unknown" and c["unknown"] == ["level_tf"]


def test_the_grade_comes_from_the_scan_once_A_is_takeable():
    """plan_trade stamps "A+" on every ticket, so after 2026-09-21 the book's
    grade cannot be trusted; the scan row's grade_raw can."""
    late = _pos(entry_date=bvc.A_TAKEABLE_SINCE)
    assert bvc.classify(late)["unknown"] == ["grade"]
    c = bvc.classify(late, {"grade_raw": "A"})
    assert c["cls"] == "in" and c["grade"] == "A" and c["grade_src"] == "scan grade_raw"
    assert bvc.classify(late, {"grade_raw": "B+"})["why"] == ["grade B+"]
    old = bvc.classify(_pos(entry_date="2026-07-01"))
    assert old["cls"] == "unknown" and old["unknown"] == ["grade source"]


def test_the_stop_is_read_at_the_plan_and_the_fill_is_flagged_separately():
    # plan stop 80 on a 100 signal = 20% (gate passes); filled at 110 = 27.3%
    c = bvc.classify(_pos(entry=110.0, risk=30.0, signal_entry=100.0))
    assert c["cls"] == "in" and c["plan_stop"] == pytest.approx(20.0)
    assert c["fill_over_cap"] and c["fill_stop"] == pytest.approx(30 / 110 * 100)


# -- freshness mirrors the deck's session + 2h rule ------------------------

def test_session_staleness_mirrors_the_deck():
    utc = dt.timezone.utc
    now = dt.datetime(2026, 9, 24, 3, 0, tzinfo=utc)          # 13:00 AEST Thu: open + 3h
    assert bvc.session_staleness("2026-09-24T08:11:50+10:00", "asx", now)["stale"] is True
    assert bvc.session_staleness("2026-09-24T11:07:00+10:00", "asx", now)["stale"] is False
    early = dt.datetime(2026, 9, 24, 0, 42, tzinfo=utc)       # 10:42 AEST: open + 42m
    v = bvc.session_staleness("2026-09-24T08:11:50+10:00", "asx", early)
    assert v["stale"] is False and v["edge"] == "close"
    sat = dt.datetime(2026, 9, 26, 12, 0, tzinfo=utc)         # weekend: Friday's close rules
    assert bvc.session_staleness("2026-09-25T16:30:00-04:00", "nasdaq", sat)["stale"] is False
    assert bvc.session_staleness("2026-09-25T15:00:00-04:00", "nasdaq", sat)["stale"] is True
    assert bvc.session_staleness("2026-09-24T00:00:00+00:00", "crypto", early)["stale"] is False
    assert bvc.session_staleness("2026-09-23T20:00:00+00:00", "crypto", early)["stale"] is True
    assert bvc.session_staleness("not a time", "asx", now)["stale"] is True


def test_prose_sections_and_the_write_fence():
    assert bvc.read_prose("@@ a\nx\ny\n@@ b\n\nz\n") == {"a": "x\ny", "b": "z"}
    hunk = "@@ -650,6 +650,12 @@ def _ticket_to_position(out: dict):"
    assert bvc.read_prose(f"@@ patch\n```diff\n{hunk}\n+x\n```\n")["patch"].count(hunk) == 1
    assert "```diff" in NOTE and "@@ -650," in NOTE and "decision[\"grade\"]" in NOTE, (
        "the section-5 patches must be in the note whole")
    src = (ROOT / "scripts" / "bot_vs_cells.py").read_text(encoding="utf-8")
    assert "git add" not in src and "write_text" not in src
    assert src.count("atomic_write(") == 2, "writes only the note and the entry-scan cache"
    git = set(re.findall(r'\["git", "(\w+)"', src))
    assert git == {"log", "show"}, git
